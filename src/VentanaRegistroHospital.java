    private void btnRegistroHospitalActionPerformed(java.awt.event.ActionEvent evt) {                                                    
       String nombre = txtNombreHospital.getText().trim();
       String resultado = gestor.registrarHospital(nombre);

       if (resultado.startsWith("ERROR")) {
           JOptionPane.showMessageDialog(this, resultado, "Error", JOptionPane.ERROR_MESSAGE);
       } else {
            txtNombreHospital.setText("");
            txtNombreHospital.requestFocus();
            // No mostrar mensaje de éxito
       }
    }                                                   

