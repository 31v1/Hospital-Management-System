    private void cargarHospitales() {
    cmbHospital.removeAllItems();
    Hospital[] hospitales = gestor.listarHospitales();
    for (Hospital h : hospitales) {
        cmbHospital.addItem(h); // 👈 Guarda el objeto completo
    }
}
    
    private void cargarTiposAtencion() {
    cmbTipoAtencion.removeAllItems();
    cmbTipoAtencion.addItem(TipoAtencion.CONSULTA);
    cmbTipoAtencion.addItem(TipoAtencion.EMERGENCIA);
    cmbTipoAtencion.addItem(TipoAtencion.CIRUGIA);
}
    private void btnRegistrarPacienteActionPerformed(java.awt.event.ActionEvent evt) {                                                     
            
        Hospital hospital = (Hospital) cmbHospital.getSelectedItem();
        int idHospital = hospital.getId();
        String nombre = txtNombrePacienteRegistro.getText().trim();
        TipoAtencion tipo = (TipoAtencion) cmbTipoAtencion.getSelectedItem();
        String resultado = gestor.registrarPaciente(hospital.getId(), nombre, tipo);

        if (resultado.startsWith("ERROR")) {
           JOptionPane.showMessageDialog(this, resultado, "Error", JOptionPane.ERROR_MESSAGE);
       } else {
            txtNombrePacienteRegistro.setText("");
            txtNombrePacienteRegistro.requestFocus();
        }
    }                                                    

