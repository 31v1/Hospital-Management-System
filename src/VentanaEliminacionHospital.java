    private void btnEliminarHospitalActionPerformed(java.awt.event.ActionEvent evt) {                                                    
        Hospital hospital = (Hospital) cmbHospital.getSelectedItem();
        if (hospital == null) {
            JOptionPane.showMessageDialog(this, "Debe seleccionar un hospital", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        String resultado = gestor.eliminarHospital(hospital.getId());
        if (resultado.startsWith("ERROR")) {
            JOptionPane.showMessageDialog(this, resultado, "Error", JOptionPane.ERROR_MESSAGE);
        } else {
            JOptionPane.showMessageDialog(this, resultado, "Éxito", JOptionPane.INFORMATION_MESSAGE);
            if (ventanaPrincipal != null) {
                ventanaPrincipal.actualizarTablas();
            }
            dispose();
        }
    }                                                   

